-- USERS
create table if not exists app_users (
    id uuid primary key references auth.users(id),
    name text not null,
    email text not null unique,
    created_at timestamptz not null default now(),
    deleted_at timestamptz,

    average_rating numeric(3,2) not null default 0
        check (average_rating >= 0 and average_rating <= 5),

    completed_trades integer not null default 0
        check (completed_trades >= 0),

    total_items_saved integer not null default 0
        check (total_items_saved >= 0)
);


-- BUNDLES
create table if not exists bundles (
    id bigint generated by default as identity primary key,

    user_id uuid not null references app_users(id),

    -- Matches the entity diagram: Offer or Request
    listing_type text not null
        check (listing_type in ('offer', 'request')),

    -- Supports your project requirements
    listing_mode text not null default 'exchange'
        check (listing_mode in ('exchange', 'giveaway')),

    -- Optional filter
    deadline timestamptz,

    pickup_location text not null,
    availability_time text not null,

    status text not null default 'active'
        check (status in (
            'active',
            'pending',
            'completed',
            'donated',
            'declined',
            'expired'
        )),

    created_at timestamptz not null default now()
);


-- ITEMS
create table if not exists items (
    id bigint generated by default as identity primary key,

    bundle_id bigint not null references bundles(id) on delete cascade,

    name text not null,

    quantity integer not null
        check (quantity > 0),

    expiration_date date,

    -- NULL means the allergen information was not specified
    is_allergen_free boolean,

    created_at timestamptz not null default now()
);


-- TRADES
create table if not exists trades (
    id bigint generated by default as identity primary key,

    offer_bundle_id bigint not null
        references bundles(id),

    request_bundle_id bigint not null
        references bundles(id),

    status text not null default 'proposed'
        check (status in (
            'proposed',
            'confirmed',
            'declined',
            'completed'
        )),

    created_at timestamptz not null default now(),

    completed_at timestamptz,

    unique (offer_bundle_id, request_bundle_id)
);


-- RATINGS
create table if not exists ratings (
    id bigint generated by default as identity primary key,

    trade_id bigint not null
        references trades(id) on delete cascade,

    reviewer_id uuid not null
        references app_users(id),

    reviewee_id uuid not null
        references app_users(id),

    score integer not null
        check (score between 1 and 5),

    created_at timestamptz not null default now(),

    check (reviewer_id <> reviewee_id),

    unique (trade_id, reviewer_id)
);


-- INDEXES
create index if not exists bundles_status_deadline_idx
    on bundles(status, deadline);

create index if not exists bundles_user_id_idx
    on bundles(user_id);

create index if not exists items_bundle_id_idx
    on items(bundle_id);

create index if not exists trades_status_idx
    on trades(status);

create index if not exists ratings_reviewee_idx
    on ratings(reviewee_id);


-- ROW LEVEL SECURITY
alter table app_users enable row level security;
alter table bundles enable row level security;
alter table items enable row level security;
alter table trades enable row level security;
alter table ratings enable row level security;